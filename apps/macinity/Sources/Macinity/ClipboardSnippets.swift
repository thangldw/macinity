import AppKit
import Foundation
import MacinityCore

struct ClipboardItem: Identifiable, Equatable {
  let id = UUID()
  let text: String
  let date: Date
}

struct Snippet: Codable, Identifiable, Equatable {
  var id = UUID()
  var name: String
  var text: String
}

/// Bounded, memory-only clipboard history. Never written to disk.
struct ClipboardHistory {
  static let maxItems = 50
  static let maxBytes = 40_000
  /// Pasteboard markers set by password managers and system services for secret/transient data.
  static let sensitiveTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
  ]

  private(set) var items: [ClipboardItem] = []

  static func isSensitive(types: [String]) -> Bool {
    !sensitiveTypes.isDisjoint(with: types)
  }

  @discardableResult
  mutating func add(_ text: String, now: Date = Date()) -> Bool {
    guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
      text.utf8.count <= Self.maxBytes
    else { return false }
    items.removeAll { $0.text == text }
    items.insert(ClipboardItem(text: text, date: now), at: 0)
    if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
    return true
  }

  mutating func remove(_ id: UUID) { items.removeAll { $0.id == id } }
  mutating func clear() { items.removeAll() }

  func filtered(_ query: String) -> [ClipboardItem] {
    let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
    guard !words.isEmpty else { return items }
    return items.filter { item in words.allSatisfy { item.text.localizedStandardContains($0) } }
  }
}

/// User-pinned snippets; small and bounded.
struct SnippetLibrary: Equatable {
  static let maxSnippets = 100
  static let maxBytes = 40_000
  private(set) var snippets: [Snippet] = []

  init(_ snippets: [Snippet] = []) { self.snippets = Array(snippets.prefix(Self.maxSnippets)) }

  @discardableResult
  mutating func add(name: String, text: String) -> Bool {
    let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !trimmed.isEmpty, !text.isEmpty, text.utf8.count <= Self.maxBytes,
      snippets.count < Self.maxSnippets
    else { return false }
    snippets.append(Snippet(name: String(trimmed.prefix(80)), text: text))
    return true
  }

  mutating func remove(_ id: UUID) { snippets.removeAll { $0.id == id } }
}

@MainActor
final class ClipboardModel: ObservableObject {
  static let recordingKey = "macinity.clipboard.recording"

  @Published private(set) var history = ClipboardHistory()
  @Published private(set) var library = SnippetLibrary()
  @Published private(set) var recording: Bool
  @Published var status = ""

  private let defaults: UserDefaults
  private let file: URL
  private var readable = true
  private var task: Task<Void, Never>?
  private var lastChange = NSPasteboard.general.changeCount

  init(
    directory: URL = AppMetadata.applicationSupportDirectory(), defaults: UserDefaults = .standard
  ) {
    self.defaults = defaults
    file = directory.appendingPathComponent("snippets-v1.json")
    recording = defaults.bool(forKey: Self.recordingKey)
    if FileManager.default.fileExists(atPath: file.path) {
      do {
        let size =
          (try FileManager.default.attributesOfItem(atPath: file.path)[.size] as? NSNumber)?
          .intValue ?? Int.max
        guard size <= 4_194_304 else { throw CocoaError(.fileReadTooLarge) }
        library = SnippetLibrary(
          try JSONDecoder().decode([Snippet].self, from: Data(contentsOf: file)))
      } catch {
        readable = false
        status = "Snippets file could not be read; existing data is preserved"
      }
    }
    if recording { startPolling() }
  }

  func setRecording(_ enabled: Bool) {
    guard enabled != recording else { return }
    recording = enabled
    defaults.set(enabled, forKey: Self.recordingKey)
    if enabled {
      startPolling()
    } else {
      task?.cancel()
      task = nil
      history.clear()
    }
  }

  private func startPolling() {
    task?.cancel()
    lastChange = NSPasteboard.general.changeCount
    task = Task { [weak self] in
      while !Task.isCancelled {
        try? await Task.sleep(for: .seconds(1))
        guard !Task.isCancelled, let self else { return }
        self.poll()
      }
    }
  }

  private func poll() {
    let board = NSPasteboard.general
    guard board.changeCount != lastChange else { return }
    lastChange = board.changeCount
    guard !ClipboardHistory.isSensitive(types: board.types?.map(\.rawValue) ?? []),
      let text = board.string(forType: .string)
    else { return }
    history.add(text)
  }

  func copy(_ text: String) {
    let board = NSPasteboard.general
    board.clearContents()
    board.setString(text, forType: .string)
    lastChange = board.changeCount
  }

  func removeItem(_ id: UUID) { history.remove(id) }
  func clearHistory() { history.clear() }

  func saveSnippet(name: String, text: String) {
    guard readable else { return }
    var updated = library
    guard updated.add(name: name, text: text) else {
      status = "Enter a name and text; at most 100 snippets are kept"
      return
    }
    persist(updated)
  }

  func removeSnippet(_ id: UUID) {
    guard readable else { return }
    var updated = library
    updated.remove(id)
    persist(updated)
  }

  private func persist(_ updated: SnippetLibrary) {
    do {
      try FileManager.default.createDirectory(
        at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
      try JSONEncoder().encode(updated.snippets).write(to: file, options: .atomic)
      library = updated
      status = ""
    } catch {
      status = "Snippets could not be saved"
    }
  }
}
